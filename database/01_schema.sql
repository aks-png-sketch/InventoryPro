-- Oracle 19c/21c/23ai. Run once in a fresh dedicated application schema.
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
CREATE TABLE users (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR2(50 CHAR) NOT NULL,
 password_hash VARCHAR2(100 CHAR) NOT NULL,
 role VARCHAR2(10 CHAR) NOT NULL,
 created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 CONSTRAINT uq_users_username UNIQUE(username),
 CONSTRAINT ck_users_role CHECK(role IN ('ADMIN','STAFF'))
);
CREATE TABLE categories (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR2(100 CHAR) NOT NULL,
 description VARCHAR2(500 CHAR),
 created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 CONSTRAINT uq_category_name UNIQUE(name)
);
CREATE TABLE suppliers (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR2(150 CHAR) NOT NULL,
 contact_person VARCHAR2(100 CHAR), email VARCHAR2(150 CHAR),
 phone VARCHAR2(30 CHAR), address VARCHAR2(500 CHAR),
 created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 CONSTRAINT uq_supplier_name UNIQUE(name)
);
CREATE TABLE products (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sku VARCHAR2(50 CHAR) NOT NULL,
 name VARCHAR2(150 CHAR) NOT NULL,
 description VARCHAR2(1000 CHAR),
 category_id NUMBER(19) NOT NULL,
 supplier_id NUMBER(19),
 unit_price NUMBER(14,2) DEFAULT 0 NOT NULL,
 quantity NUMBER(9,0) DEFAULT 0 NOT NULL,
 reorder_level NUMBER(9,0) DEFAULT 10 NOT NULL,
 created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 CONSTRAINT uq_product_sku UNIQUE(sku),
 CONSTRAINT fk_product_category FOREIGN KEY(category_id) REFERENCES categories(id),
 CONSTRAINT fk_product_supplier FOREIGN KEY(supplier_id) REFERENCES suppliers(id),
 CONSTRAINT ck_price CHECK(unit_price>=0),
 CONSTRAINT ck_quantity CHECK(quantity>=0),
 CONSTRAINT ck_reorder CHECK(reorder_level>=0)
);
CREATE TABLE stock_movements (
 id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 product_id NUMBER(19) NOT NULL,
 user_id NUMBER(19) NOT NULL,
 movement_type VARCHAR2(3 CHAR) NOT NULL,
 quantity NUMBER(9,0) NOT NULL,
 reason VARCHAR2(500 CHAR) NOT NULL,
 balance_after NUMBER(9,0) NOT NULL,
 created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 CONSTRAINT fk_movement_product FOREIGN KEY(product_id) REFERENCES products(id),
 CONSTRAINT fk_movement_user FOREIGN KEY(user_id) REFERENCES users(id),
 CONSTRAINT ck_movement_type CHECK(movement_type IN ('IN','OUT')),
 CONSTRAINT ck_movement_quantity CHECK(quantity>0),
 CONSTRAINT ck_movement_balance CHECK(balance_after>=0)
);
CREATE INDEX ix_products_category ON products(category_id);
CREATE INDEX ix_products_supplier ON products(supplier_id);
CREATE INDEX ix_movements_product ON stock_movements(product_id);
CREATE INDEX ix_movements_user ON stock_movements(user_id);
CREATE INDEX ix_movements_date ON stock_movements(created_at);
-- DDL implicitly commits in Oracle. No DROP statements against application tables.
